import json
from pathlib import Path
from typing import Any

from ragworkbench.boards.board_model import CacheMode
from ragworkbench.caching.abstract_file_system_cache import AbstractFileSystemCache


class TrackingKeyCache(AbstractFileSystemCache):
    """
    Cache for API tracking keys generated by the cost tracker.

    This cache stores generated API keys to avoid regenerating them for the same
    configuration, which helps maintain consistent tracking across runs.
    """

    def __init__(
        self,
        cache_dir: Path | str,
        config_dict: dict[str, Any] | None = None,
        cache_mode: CacheMode = CacheMode.ON,
    ):
        """
        Initialize tracking key cache.

        Args:
            cache_dir: Base directory for the cache
            config_dict: Configuration dictionary to include in cache key
            cache_mode: Cache operation mode (on/off/refresh)
        """
        super().__init__(
            cache_dir,
            "tracking_keys",
            config_dict=config_dict,
            cache_mode=cache_mode,
        )

    def _read_content(self, file: Path) -> str:
        """
        Read API key from cache file.

        Args:
            file: Path to the cache file

        Returns:
            The cached API key string
        """
        cached_data: dict[str, Any] = json.loads(file.read_text(encoding="utf-8"))
        api_key: str = cached_data.get("api_key", "")
        return api_key

    def _content_to_json(self, api_key: str) -> str:
        return json.dumps({"api_key": api_key}, indent=4)

    def _get_parameters_hash(self, config_hash: str) -> str:
        return AbstractFileSystemCache.get_hash_string(config_hash)

    # We force signature
    def get(self, config_hash: str) -> str | None:
        cached_value, cache_key = super()._get(config_hash)
        return cached_value

    # We force signature
    def add(
        self,
        config_hash: str,
        api_key: str,
    ):
        super().add(config_hash, api_key)


