class DatasetRegistry(StrictBaseModel):
    _datasets: list[DatasetRecord] = _DATASETS

    def filter(
        self,
        *,
        domains: list[DatasetDomain] | None = None,
        retrieval_hops: list[DatasetRetrievalHops] | None = None,
        answer_scopes: list[DatasetAnswerScope] | None = None,
        context_dependencies: list[DatasetQuestionContextDependency] | None = None,
        target_modalities: list[DatasetTargetModality] | None = None,
        document_structure_format: DatasetDocumentStructureFormat | None = None,
        include_private_datasets: bool = False,
    ) -> list[DatasetRecord]:
        results: list[DatasetRecord] = []

        for record in self._datasets:
            # NEW: Skip private datasets unless explicitly allowed
            if not include_private_datasets and record.is_private_dataset:
                continue

            if domains is not None and record.domain not in domains:
                continue

            if (
                retrieval_hops is not None
                and record.retrieval_hops not in retrieval_hops
            ):
                continue

            if answer_scopes is not None and record.answer_scope not in answer_scopes:
                continue

            if (
                context_dependencies is not None
                and record.question_context_dependency not in context_dependencies
            ):
                continue

            if target_modalities is not None:
                if not any(
                    modality in target_modalities
                    for modality in record.targeted_modalities
                ):
                    continue

            if (
                document_structure_format is not None
                and record.document_structure_format not in document_structure_format
            ):
                continue

            results.append(record)

        return results

    def list(self) -> list[DatasetRecord]:
        return self._datasets
